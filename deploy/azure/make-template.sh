# Writes azuredeploy.json — the ARM template behind the Deploy to Azure
# button and deploy.sh — with guest.sh embedded as the VM's cloud-init
# custom data (base64). The template is committed; this script keeps it
# equal to guest.sh: `make-template.sh` rewrites it, `make-template.sh
# --check` fails when the committed one is stale (the kit runs the check).
#
# Usage: make-template.sh [--check] [OUT]      (default OUT: azuredeploy.json beside this script)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
CHECK=0; [ "${1:-}" = "--check" ] && { CHECK=1; shift; }
OUT="${1:-$HERE/azuredeploy.json}"
CUSTOM_DATA="$(base64 < "$HERE/guest.sh" | tr -d '\n')"
[ "${#CUSTOM_DATA}" -le 65536 ] || { echo "guest.sh is too large for custom data (${#CUSTOM_DATA} bytes of base64; the limit is 64 KiB)" >&2; exit 1; }
TMP="$(mktemp)"
CUSTOM_DATA="$CUSTOM_DATA" python3 - "$TMP" <<'PY'
