      "properties": {
        "hardwareProfile": {"vmSize": "[parameters('vmSize')]"},
        "securityProfile": {"securityType": "ConfidentialVM", "uefiSettings": {"secureBootEnabled": True, "vTpmEnabled": True}},
        "storageProfile": {
          "imageReference": {"publisher": "Canonical", "offer": "ubuntu-24_04-lts", "sku": "cvm", "version": "latest"},
          "osDisk": {"name": "[variables('diskName')]", "createOption": "FromImage", "diskSizeGB": 32, "deleteOption": "Delete",
                     "managedDisk": {"storageAccountType": "Premium_LRS", "securityProfile": {"securityEncryptionType": "DiskWithVMGuestState"}}}
        },
        "osProfile": {
          "computerName": "[parameters('vmName')]", "adminUsername": "[parameters('adminUsername')]", "customData": "[variables('customData')]",
