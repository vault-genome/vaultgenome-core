      "properties": {"addressSpace": {"addressPrefixes": ["10.42.0.0/16"]}, "subnets": [
        {"name": "[variables('subnetName')]", "properties": {"addressPrefix": "10.42.0.0/24", "networkSecurityGroup": {"id": "[resourceId('Microsoft.Network/networkSecurityGroups', variables('nsgName'))]"}}}
      ]}
    },
    {
      "type": "Microsoft.Network/publicIPAddresses", "apiVersion": "2023-11-01", "name": "[variables('pipName')]", "location": "[parameters('location')]", "tags": "[variables('tags')]",
