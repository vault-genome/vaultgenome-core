    "customData": custom
  },
  "resources": [
    {
      "type": "Microsoft.Network/networkSecurityGroups", "apiVersion": "2023-11-01", "name": "[variables('nsgName')]", "location": "[parameters('location')]", "tags": "[variables('tags')]",
      "properties": {"securityRules": [
        {"name": "ssh", "properties": {"priority": 1000, "direction": "Inbound", "access": "Allow", "protocol": "Tcp", "sourceAddressPrefix": "[parameters('sshSourcePrefix')]", "sourcePortRange": "*", "destinationAddressPrefix": "*", "destinationPortRange": "22"}}
      ]}
    },
    {
      "type": "Microsoft.Network/virtualNetworks", "apiVersion": "2023-11-01", "name": "[variables('vnetName')]", "location": "[parameters('location')]", "tags": "[variables('tags')]",
