# Writes template.json — the CloudFormation template behind the Launch
# Stack button and deploy.sh — with guest.sh embedded as the instance's
# user data (gzip, base64: EC2 holds user data to 16 KB before base64, and
# cloud-init uncompresses gzip). The template is committed; this script
# keeps it equal to guest.sh: `make-template.sh` rewrites it,
# `make-template.sh --check` fails when the committed one is stale (the
# kit runs the check).
#
# Usage: make-template.sh [--check] [OUT]      (default OUT: template.json beside this script)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
CHECK=0; [ "${1:-}" = "--check" ] && { CHECK=1; shift; }
OUT="${1:-$HERE/template.json}"
GZ_BYTES="$(gzip -9nc < "$HERE/guest.sh" | wc -c | tr -d ' ')"
[ "$GZ_BYTES" -le 16384 ] || { echo "guest.sh is too large for user data (${GZ_BYTES} bytes gzipped; the limit is 16 KB)" >&2; exit 1; }
USER_DATA="$(gzip -9nc < "$HERE/guest.sh" | base64 | tr -d '\n')"
TMP="$(mktemp)"
USER_DATA="$USER_DATA" python3 - "$TMP" <<'PY'
