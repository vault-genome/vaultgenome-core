[ "$SIZE" -le 51200 ] || { echo "template.json is $SIZE bytes; the CloudFormation limit for a template passed by value is 51 200" >&2; rm -f "$TMP"; exit 1; }
if [ "$CHECK" = 1 ]; then
  if cmp -s "$TMP" "$OUT"; then echo "template.json is current"; rm -f "$TMP"; exit 0; fi
  echo "template.json is stale: run deploy/aws/make-template.sh and commit it" >&2; rm -f "$TMP"; exit 1
fi
mv "$TMP" "$OUT"; echo "wrote $OUT ($SIZE bytes; user data $GZ_BYTES bytes gzipped, ${#USER_DATA} bytes of base64)"
