"""Write the ProVerif models of the protocols from one template per protocol, so that the
variants differ only in the lines that change between them. Part one, the cross-cloud key
release, is described here; part two, the Return Path handshake, before its template below.

The protocol modelled is the one the daemons run (ADR 0009, 0029, 0010, 0011; `kms.Coordinator`,
`crosscloud.Receiver`, `genome/receipt`): the source authority signs a handshake request with a
fresh nonce; the destination generates a recipient key for that request alone and has its TEE
quote over the key-binding challenge h(label, suite, pk, nonce); the source verifies the quote
under the challenge it recomputes, applies the operator's stop list and the allow-list, records
the authorization, and encapsulates the key to the recipient key with the token's binding as
additional data; the destination opens under the key of that request only, once, and its TEE
quotes over the restore receipt the source confirms.

The attacker is the network. A genuine chip the operator did not list (`meas_bad`) answers any
challenge for the attacker. Queries, in the order the tool prints them:
  S   the released key stays secret (attacker(dek) is false)
  A1  a key the destination opened was authorized by the source for that decision
  A2  the source authorizes only to a key the honest destination generated for the request
      (injective: one authorization per key)
  A3  every opening corresponds to one release (no replay)
  P   no authorization after the operator's stop is on the record (AuthorizedIn(ph1) unreachable)
  R   every confirmation corresponds to one restore the chip vouched for (injective)
  M   no authorization to the unlisted chip (Authorized(_, meas_bad, _) unreachable)
The variants each remove one protection or leak one key, to state what each guarantee rests on.
"""
