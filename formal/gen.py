# Part two: the Return Path handshake (ADR 0014, 0025; internal/compute/returnpath/transport).
# The worker (the client) opens a mutual-TLS connection to the vault (the server) and sends
# HELLO_CLIENT with a fresh nonce and a proposed challenge; the vault answers HELLO_SERVER with its
# nonce, its chip's quote over h(SERVER-ATT, client nonce, proposed challenge) and the derivation
# context; the worker verifies that quote at the vault's pinned measurement and sends
# ATTEST_CLIENT, its chip's quote over h(CLIENT-ATT, client nonce, server nonce, context); the
# vault verifies it at the worker's pinned measurement and admits the session; both derive the
# frame MAC keys by HKDF over the two nonces and the context. The job's material is sealed with
# the session sealing key the two daemons share (keys.session_sealing), with the manifest as
# additional data; the worker signs the candidate with its registry key; the vault judges it and
# signs the verdict over the candidate's digest. Queries, in the order the tool prints them:
#   S   the sealed material (payload) stays secret
#   C   the candidate stays secret
#   K   a value sealed under the frame MAC key stays secret (the MAC keys are not the attacker's)
#   W   every admission corresponds to one quote the honest worker's chip made over that session
#   M   no admission of the unlisted chip
#   V   every acceptance of the vault's quote corresponds to one quote the vault's chip made for
#       that nonce
#   J   every verdict corresponds to one candidate the honest worker produced for that manifest
#   I   every candidate the worker produced corresponds to one job the vault issued (no replay)
# The attacker is the network, holds a certificate the vault's TLS accepts (the rogue of the
# kits), and has the unlisted chip's quotes for the asking.

TEMPLATE_RP = """(* {title}
   Generated by gen.py; do not edit by hand. ProVerif 2.05 syntax.
   Copyright (C) 2026 Serhii Nikolaichuk, Rodion Sorokin
   SPDX-License-Identifier: AGPL-3.0-or-later *)

free c: channel.

type skey.
type pkey.
type key.
fun pk(skey): pkey.
fun k2b(key): bitstring [data].

fun sign(bitstring, skey): bitstring.
reduc forall m: bitstring, k: skey; checksig(sign(m, k), pk(k)) = m.

fun h(bitstring): bitstring.

(* Mutual TLS, abstracted: the client sends a fresh connection key under the server's certificate
   key, authenticated by its own certificate key; the records of the connection are encrypted
   under that key. *)
fun aenc_auth(bitstring, pkey, skey): bitstring.
reduc forall m: bitstring, kr: skey, ks: skey; adec_auth(aenc_auth(m, pk(kr), ks), kr, pk(ks)) = m.
fun senc(bitstring, key): bitstring.
reduc forall m: bitstring, k: key; sdec(senc(m, k), k) = m.

(* AES-256-GCM with additional data, under the session sealing key the daemons share. *)
fun aead(bitstring, key, bitstring, bitstring): bitstring.
reduc forall m: bitstring, k: key, n: bitstring, a: bitstring; aead_open(aead(m, k, n, a), k, n, a) = m.

(* HKDF over the transcript: the frame MAC keys. *)
fun hkdf(bitstring): key.

free tk: skey [private].       (* the chips' attestation key, under the vendor root *)
free skV: skey [private].      (* the vault's TLS certificate key *)
free skW: skey [private].      (* the worker's TLS certificate key *)
free skR: skey.                (* a certificate the vault's TLS accepts, in the attacker's hands *)
free skA: skey [private].      (* the authority's signing key: the verdict *)
free skS: skey [private].      (* the worker's signing key, pinned in the vault's registry *)
free kseal: key [private].     (* keys.session_sealing, shared by the daemons, sealed to each host *)
free payload: bitstring [private]. (* the material a job discloses *)

const meas_V: bitstring.       (* the vault's measurement, pinned by the worker *)
const meas_W: bitstring.       (* the worker's measurement, pinned by the vault *)
const meas_bad: bitstring.     (* a genuine chip neither pins *)
const labelS: bitstring.       (* "rp-wire-v1.0 SERVER-ATT" *)
const labelC: bitstring.       (* "rp-wire-v1.0 CLIENT-ATT" *)
const labelK: bitstring.       (* "rp-wire-v1.0 hkdf-salt" and "session-mac" *)
const HELLO_CLIENT: bitstring.
const HELLO_SERVER: bitstring.
const ATTEST_CLIENT: bitstring.
const SESSION_READY: bitstring.
const JOB: bitstring.
const CAND: bitstring.
const VERDICT: bitstring.
const kidW: bitstring.         (* the worker's key id in the registry *)

event VaultQuoted(bitstring, bitstring).
event VaultVerified(bitstring, bitstring, bitstring).
event WorkerQuoted(bitstring, bitstring, bitstring).
event Admitted(bitstring, bitstring, bitstring, bitstring).
event Issued(bitstring).
event Produced(bitstring, bitstring).
event Judged(bitstring, bitstring).

query attacker(payload).
query attacker(new cand).
query attacker(new probe).
query mw: bitstring, nc: bitstring, ns: bitstring, ctx: bitstring; inj-event(Admitted(mw, nc, ns, ctx)) ==> inj-event(WorkerQuoted(nc, ns, ctx)).
query nc: bitstring, ns: bitstring, ctx: bitstring; event(Admitted(meas_bad, nc, ns, ctx)).
query mv: bitstring, nc: bitstring, prop: bitstring; inj-event(VaultVerified(mv, nc, prop)) ==> inj-event(VaultQuoted(nc, prop)).
query mf: bitstring, cand: bitstring; inj-event(Judged(mf, cand)) ==> inj-event(Produced(mf, cand)).
query mf: bitstring, cand: bitstring; inj-event(Produced(mf, cand)) ==> inj-event(Issued(mf)).

(* The vault, one session: the handshake, one job, one verdict. *)
let Vault =
  in(c, (pkc: pkey, hello: bitstring));
  let k2b(k) = adec_auth(hello, skV, pkc) in
  in(c, m1: bitstring);
  let (=HELLO_CLIENT, nc: bitstring, prop: bitstring) = sdec(m1, k) in
  new ns: bitstring; new ctx: bitstring;
  event VaultQuoted(nc, prop);
  out(c, senc((HELLO_SERVER, nc, ns, sign((meas_V, {CHAL_S}), tk), ctx), k));
  in(c, m3: bitstring);
  let (=ATTEST_CLIENT, ev: bitstring) = sdec(m3, k) in
  let (mw: bitstring, rd: bitstring) = checksig(ev, pk(tk)) in
  if rd = {CHAL_C} then
  if mw = meas_W then
  event Admitted(mw, nc, ns, ctx);
  out(c, senc(SESSION_READY, k));
  new manifest: bitstring; new sn: bitstring;
  event Issued(manifest);
  out(c, senc((JOB, manifest, sn, aead(payload, kseal, sn, manifest)), k));
  in(c, m5: bitstring);
  let (=CAND, mf: bitstring, cand: bitstring, kid: bitstring, sg: bitstring) = sdec(m5, k) in
  if mf = manifest then
  if kid = kidW then
  let (=mf, =cand, =kid) = checksig(sg, pk(skS)) in
  event Judged(manifest, cand);
  out(c, sign((VERDICT, manifest, h(cand)), skA)).

(* The worker, one session: the connection, the handshake, one job, one candidate. *)
let Worker =
  new k: key;
  out(c, (pk(skW), aenc_auth(k2b(k), pk(skV), skW)));
{OPEN_CHANNEL}  new nc: bitstring; new prop: bitstring;
  out(c, senc((HELLO_CLIENT, nc, prop), k));
  in(c, m2: bitstring);
  let (=HELLO_SERVER, =nc, ns: bitstring, evS: bitstring, ctx: bitstring) = sdec(m2, k) in
  let (mv: bitstring, rd: bitstring) = checksig(evS, pk(tk)) in
  if rd = {CHAL_S} then
  if mv = meas_V then
  event VaultVerified(mv, nc, prop);
  event WorkerQuoted(nc, ns, ctx);
  out(c, senc((ATTEST_CLIENT, sign((meas_W, {CHAL_C}), tk)), k));
  in(c, m4: bitstring);
  if sdec(m4, k) = SESSION_READY then
  let kmac = hkdf((labelK, nc, ns, ctx)) in
  new probe: bitstring;
  out(c, senc(probe, kmac));
  in(c, m5: bitstring);
  let (=JOB, manifest: bitstring, sn: bitstring, sealed: bitstring) = sdec(m5, k) in
  let material = aead_open(sealed, kseal, sn, manifest) in
  new cand: bitstring;
  event Produced(manifest, cand);
  out(c, senc((CAND, manifest, cand, kidW, sign((manifest, cand, kidW), skS)), k)).

(* A genuine chip neither side pins: it quotes over whatever the attacker asks. *)
let Impostor =
  in(c, chal: bitstring);
  out(c, sign((meas_bad, chal), tk)).

process
  out(c, pk(tk)); out(c, pk(skV)); out(c, pk(skW)); out(c, pk(skA)); out(c, pk(skS));
{LEAK}  ( !Vault | !Worker | !Impostor )
"""

