"""Write the ProVerif models of the cross-cloud key release from one template, so that the
variants differ only in the lines that change between them.

The protocol modelled is the one the daemons run (ADR 0009, 0029, 0010, 0011; `kms.Coordinator`,
`crosscloud.Receiver`, `genome/receipt`): the source authority signs a handshake request with a
fresh nonce; the destination generates a recipient key for that request alone and has its TEE
quote over the key-binding challenge h(label, suite, pk, nonce); the source verifies the quote
under the challenge it recomputes, applies the operator's stop list and the allow-list, records
the authorization, and encapsulates the key to the recipient key with the token's binding as
additional data; the destination opens under the key of that request only, once, and its TEE
quotes over the restore receipt the source confirms.

The attacker is the network. A genuine chip the operator did not list (`meas_bad`) answers any
challenge for the attacker. Queries, in the order the tool prints them:
  S   the released key stays secret (attacker(dek) is false)
  A1  a key the destination opened was authorized by the source for that decision
  A2  the source authorizes only to a key the honest destination generated for the request
      (injective: one authorization per key)
  A3  every opening corresponds to one release (no replay)
  P   no authorization after the operator's stop is on the record (AuthorizedIn(ph1) unreachable)
  R   every confirmation corresponds to one restore the chip vouched for (injective)
  M   no authorization to the unlisted chip (Authorized(_, meas_bad, _) unreachable)
The variants each remove one protection or leak one key, to state what each guarantee rests on.
"""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent

TEMPLATE = """(* {title}
   Generated by gen.py; do not edit by hand. ProVerif 2.05 syntax.
   Copyright (C) 2026 Serhii Nikolaichuk, Rodion Sorokin
   SPDX-License-Identifier: AGPL-3.0-or-later *)

free c: channel.

type skey.
type pkey.
fun pk(skey): pkey.
fun pk2b(pkey): bitstring [data].

fun sign(bitstring, skey): bitstring.
reduc forall m: bitstring, k: skey; checksig(sign(m, k), pk(k)) = m.

fun h(bitstring): bitstring.

const meas_ok: bitstring.      (* the measurement on the allow-list *)
const meas_bad: bitstring.     (* a genuine chip the operator did not list *)
const suite_strong: bitstring.
const suite_weak: bitstring.
const kid1: bitstring.         (* the key id released *)
const kind: bitstring.
const label_bind: bitstring.   (* "vault-genome xcc-kem-bind v2" *)
const label_rcpt: bitstring.   (* "vault-genome restore-receipt v1" *)
const s0: bitstring.           (* stop-list serials *)
const s1: bitstring.
const nostop: bitstring.
const stopall: bitstring.
const ph0: bitstring.          (* before the stop is on the record *)
const ph1: bitstring.          (* after it *)

(* HPKE in base mode, with additional data: the suite the destination generated its key for. *)
fun hpke(bitstring, pkey, bitstring): bitstring.
reduc forall m: bitstring, k: skey, a: bitstring; hpke_open(hpke(m, pk(k), a), k, a) = m.
(* A suite the attacker can open: any suite the source accepts and the destination did not
   generate its key for. *)
fun hpke_weak(bitstring, pkey, bitstring): bitstring.
reduc forall m: bitstring, k: skey, a: bitstring; hpke_weak_open(hpke_weak(m, pk(k), a), k, a) = m.
reduc forall m: bitstring, p: pkey, a: bitstring; hpke_weak_break(hpke_weak(m, p, a)) = m.
(* The source wraps under the suite the answer names. *)
fun wrap(bitstring, bitstring, pkey, bitstring): bitstring
  reduc forall m: bitstring, p: pkey, a: bitstring; wrap(suite_strong, m, p, a) = hpke(m, p, a)
  otherwise forall m: bitstring, p: pkey, a: bitstring; wrap(suite_weak, m, p, a) = hpke_weak(m, p, a).

free tk: skey [private].       (* the chips' attestation key, under the vendor root *)
free skS: skey [private].      (* the source authority's signing key *)
free skO: skey [private].      (* the operator's key, which signs stop lists *)
free dek: bitstring [private]. (* the genome key the source releases *)
{SHARED_KEY_DECL}

event Generated(pkey, bitstring).
event Authorized(bitstring, bitstring, pkey).
event AuthorizedIn(bitstring).
event Released(bitstring, bitstring, bitstring).
event Opened(bitstring, bitstring).
event Restored(bitstring, bitstring, bitstring).
event Confirmed(bitstring, bitstring, bitstring).

query attacker(dek).
query d: bitstring, k: bitstring, m: bitstring, p: pkey; event(Opened(d, k)) ==> event(Authorized(d, m, p)).
query d: bitstring, m: bitstring, p: pkey, n: bitstring; inj-event(Authorized(d, m, p)) ==> inj-event(Generated(p, n)).
query t: bitstring, d: bitstring, k: bitstring; inj-event(Opened(d, k)) ==> inj-event(Released(t, d, k)).
query event(AuthorizedIn(ph1)).
query d: bitstring, kid: bitstring, m: bitstring; inj-event(Confirmed(d, kid, m)) ==> inj-event(Restored(d, kid, m)).
query d: bitstring, p: pkey; event(Authorized(d, meas_bad, p)).

(* The source authority, one release: ser is the newest stop-list serial on its record. *)
let Source(ser: bitstring, ph: bitstring) =
  new reqid: bitstring; new decid: bitstring; new n: bitstring;
  out(c, sign((reqid, decid, n, kind), skS));
  in(c, (suite: bitstring, pkb: bitstring, ev: bitstring));
  let pk2b(pkh) = pkb in
  let (m: bitstring, rd: bitstring) = checksig(ev, pk(tk)) in
  if rd = {BIND_SRC} then
  in(c, sl: bitstring);
  let (serial: bitstring, flag: bitstring) = checksig(sl, pk(skO)) in
{MONO}  if flag = nostop then
  if m = meas_ok then
  new tokenid: bitstring;
  let aad = h((tokenid, m, kid1)) in
  event Authorized(decid, m, pkh);
  event AuthorizedIn(ph);
  let ct = wrap(suite, dek, pkh, aad) in
  event Released(tokenid, decid, dek);
  out(c, sign((tokenid, decid, reqid, m, kid1, suite, ct, aad), skS));
  in(c, (rcpt: bitstring, q: bitstring));
  let (mr: bitstring, rdr: bitstring) = checksig(q, pk(tk)) in
  if mr = m then
  if rdr = h((label_rcpt, rcpt)) then
{RCPT_SRC}
  event Confirmed(decid, kid1, m).

(* The destination, at the listed measurement: one handshake, one key, one token. *)
let Dest =
  in(c, req: bitstring);
  let (reqid: bitstring, decid: bitstring, n: bitstring, k: bitstring) = checksig(req, pk(skS)) in
{DEST_KEY}
  event Generated(pk(hk), n);
  let pkb = pk2b(pk(hk)) in
  out(c, (suite_strong, pkb, sign((meas_ok, {BIND_DST}), tk)));
  in(c, tok: bitstring);
  let (tokenid: bitstring, decid2: bitstring, reqid2: bitstring, m: bitstring, kid: bitstring, suite: bitstring, ct: bitstring, aad: bitstring) = checksig(tok, pk(skS)) in
  if decid2 = decid then
  if reqid2 = reqid then
  if aad = h((tokenid, m, kid)) then
  if suite = suite_strong then
  let x = hpke_open(ct, hk, aad) in
  event Opened(decid, x);
{RCPT_DST}
  event Restored(decid, kid, meas_ok);
  out(c, (rcpt, sign((meas_ok, h((label_rcpt, rcpt))), tk))).

(* A genuine chip the operator did not list: it quotes over whatever the attacker asks. *)
let Impostor =
  in(c, chal: bitstring);
  out(c, sign((meas_bad, chal), tk)).

process
  out(c, pk(tk)); out(c, pk(skS)); out(c, pk(skO));
{LEAK}  out(c, sign((s0, nostop), skO));
  ( !Source(s0, ph0) | !Dest | !Impostor
  | phase 1; ( out(c, sign((s1, stopall), skO)){LEAK_PHASE1} | !Source(s1, ph1) | !Dest | !Impostor ) )
"""

BASE = dict(
    SHARED_KEY_DECL="",
    BIND_SRC="h((label_bind, suite, pkb, n))",
    BIND_DST="h((label_bind, suite_strong, pkb, n))",
    MONO="  if serial = ser then\n",
    RCPT_SRC="  let (rkid: bitstring, rdec: bitstring, rreq: bitstring, rtok: bitstring, rm: bitstring) = rcpt in\n  if rdec = decid then\n  if rkid = kid1 then\n  if rm = m then",
    RCPT_DST="  let rcpt = (kid, decid, reqid, tokenid, meas_ok) in",
    DEST_KEY="  new hk: skey;",
    LEAK="",
    LEAK_PHASE1="",
)

VARIANTS = {
    "keyrelease-base.pv": dict(
        title="The cross-cloud key release as the daemons run it (ADR 0009, 0029, 0010, 0011)"),
    "keyrelease-nobind.pv": dict(
        title="Without the key binding: the challenge covers the nonce alone (the derivation ADR 0009 replaced)",
        BIND_SRC="h((label_bind, n))", BIND_DST="h((label_bind, n))"),
    "keyrelease-nosuitebind.pv": dict(
        title="Without the suite in the binding: the v1 challenge of ADR 0009, before ADR 0029 bound the suite",
        BIND_SRC="h((label_bind, pkb, n))", BIND_DST="h((label_bind, pkb, n))"),
    "keyrelease-sharedkey.pv": dict(
        title="One recipient key for every handshake, leaked after the release (the first version of ADR 0009)",
        SHARED_KEY_DECL="free hkL: skey [private].   (* the one recipient key of the first version *)\n",
        DEST_KEY="  let hk = hkL in",
        LEAK_PHASE1=" | out(c, hkL)"),
    "keyrelease-stop-rollback.pv": dict(
        title="Without the stop list's no-rollback rule: the source accepts any list the operator ever signed",
        MONO=""),
    "keyrelease-receipt-nodecision.pv": dict(
        title="A restore receipt that names the key and the measurement but not the decision",
        RCPT_SRC="  let (rkid: bitstring, rm: bitstring) = rcpt in\n  if rkid = kid1 then\n  if rm = m then",
        RCPT_DST="  let rcpt = (kid, meas_ok) in"),
    "keyrelease-tee-key-leaked.pv": dict(
        title="The chips' attestation key has leaked",
        LEAK="  out(c, tk);\n"),
    "keyrelease-authority-key-leaked.pv": dict(
        title="The source authority's signing key has leaked",
        LEAK="  out(c, skS);\n"),
}


def main():
    for name, knobs in VARIANTS.items():
        fields = dict(BASE)
        fields.update(knobs)
        (HERE / name).write_text(TEMPLATE.format(**fields), encoding="utf-8")


if __name__ == "__main__":
    main()
