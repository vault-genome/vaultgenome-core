# Part three: the sentinel and the policy-driven failover (ADR 0012, 0017; internal/genome/sentinel,
# internal/vault/failover, sagvd failover). The operator signs a failover policy: its serial, the
# sentinel's key, the primary's measurement and the one standby's measurement. The sentinel on the
# primary seals each generation — the genome key encapsulated to the authority's escrow key, the
# primary keeping nothing that opens it — and writes the seal record signed with its key and, with
# --tee, quoted by the primary's chip over the record; a compromise report, naming the last
# generation it sealed, the same way. The executor on the authority accepts from the outbox only
# records that verify under the policy's sentinel key and carry the primary chip's quote at the
# pinned measurement; on a trigger it chooses the newest generation at or before the last the
# sentinel reported, records the decision, opens the key from escrow and
# releases it through the attested release of part one, to the standby the policy names and no
# other, under the operator's stop list. Queries, in the order the tool prints them:
#   G   the genome key stays secret (the primary and the outbox hold ciphertext)
#   F1  every failover corresponds to a policy the operator issued (that one serial performs at
#       most one failover is a property of the authority's record, which the symbolic model does
#       not establish)
#   F2  the key is released only to the measurement the policy names (not the primary's, not the
#       model's, not the outbox's choice)
#   F3  every trigger acted on is a report the sentinel wrote on its chip
#   F4  every generation chosen is one the sentinel sealed on its chip
#   F5  every opening on the standby corresponds to a decision
#   P   no release once the operator's stop is on the record
# The attacker is the network and the outbox (anyone who can write to it); the variants give it
# the sentinel's seed off the chip, the primary itself (the seed and the chip's quotes at the
# primary's measurement), or remove one rule.

